/**
 * Writes packages/fixtures/near/vectors.json: NEP-413 sign-in, quote signature and NEP-366 delegate
 * bytes and signatures, made with near-api-js and the backend's own code, for the app to check its
 * borsh and signing against. Run after changing a NEAR format: npm run near:vectors
 * test/near-vectors.test.ts fails if the committed file is out of date.
 *
 * The keys are the public RFC 8032 Ed25519 test vectors (the same as contracts-near's quote fixture):
 * TEST ONLY, never for real funds.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { KeyPairSigner, actions, buildDelegateAction, encodeDelegateAction, encodeSignedDelegate } from 'near-api-js';
import type { Address, Hex } from 'viem';
import { keyPairFromSeed } from '../src/adapters/near/keys.js';
import { NearQuoteSigner } from '../src/adapters/near/near-quote-signer.js';
import { NEP413_TAG, nep413Hash } from '../src/adapters/near/nep413.js';
import { nearQuoteJson, nearTransferMsg } from '../src/adapters/near/quote-message.js';
import type { Quote } from '../src/domain/quote.js';

export const VECTORS_PATH = fileURLToPath(new URL('../../../packages/fixtures/near/vectors.json', import.meta.url));

/** RFC 8032 section 7.1, tests 1 and 2. */
export const QUOTE_SIGNER_SEED = '9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60';
export const PAYER_SEED = '4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb';

const hex = (bytes: Uint8Array) => Buffer.from(bytes).toString('hex');
const base64 = (bytes: Uint8Array) => Buffer.from(bytes).toString('base64');

export async function renderNearVectors(): Promise<string> {
  const quoteSignerKey = keyPairFromSeed(Buffer.from(QUOTE_SIGNER_SEED, 'hex'));
  const payerKey = keyPairFromSeed(Buffer.from(PAYER_SEED, 'hex'));
  const payer = hex(payerKey.getPublicKey().data);
  const payerSigner = new KeyPairSigner(payerKey);

  // NEP-413 sign-in, with the message the backend writes.
  const nonce = createHash('sha256').update('globalpay-near-vectors:nonce').digest();
  const message =
    `globalpay.local wants you to sign in to GlobalPay with your NEAR account:\n${payer}\n\n` +
    `Nonce: ${hex(nonce)}\nIssued At: 2026-11-14T12:00:00.000Z\nExpiration Time: 2026-11-14T12:05:00.000Z`;
  const signIn = await payerSigner.signNep413Message(payer, { message, recipient: 'globalpay.local', nonce });

  // The quote (contracts-near/settlement/tests/fixtures/quote.json's), its signature and msg.
  const quote = {
    quoteId: '0xd213c5383d59bc060266adae2f78f8a54a4c50583c442beb888893df13746e9f' as Hex,
    payer: payer as Address,
    token: 'test-usdc.testnet' as Address,
    tokenAmount: 2_850_000n,
    fiat: { currency: 'THB', minor: 10_000n },
    merchantRefHash: '0x33b9c6437277fd4075ab90fd462a5d08797ea1f845c6bcaac42479041bf746be' as Hex,
    expiresAt: new Date(1_800_000_060_000),
  } as Quote;
  const quoteSignature = await new NearQuoteSigner(quoteSignerKey.toString()).sign(quote);
  const msg = nearTransferMsg(quote, quoteSignature);

  // The delegate action the app signs for that quote.
  const args = { receiver_id: 'settlement.testnet', amount: '2850000', msg };
  const delegateAction = buildDelegateAction({
    senderId: payer,
    receiverId: 'test-usdc.testnet',
    actions: [actions.functionCall('ft_transfer_call', args, 100_000_000_000_000n, 1n)],
    nonce: 190_000_000_000_042n,
    maxBlockHeight: 190_000_300n,
    publicKey: payerKey.getPublicKey(),
  });
  const encoded = encodeDelegateAction(delegateAction);
  const { signedDelegate, delegateHash } = await payerSigner.signDelegateAction(delegateAction);

  const vectors = {
    _comment:
      'TEST ONLY. Keys are the public RFC 8032 Ed25519 test vectors. Generated by services/api/scripts/near-vectors.ts (npm run near:vectors).',
    keys: {
      quote_signer: { seed_hex: QUOTE_SIGNER_SEED, public_key: quoteSignerKey.getPublicKey().toString() },
      payer: { seed_hex: PAYER_SEED, public_key: payerKey.getPublicKey().toString(), account_id: payer },
    },
    nep413: {
      tag: NEP413_TAG,
      message,
      nonce_hex: hex(nonce),
      recipient: 'globalpay.local',
      hash_hex: hex(nep413Hash({ message, nonce, recipient: 'globalpay.local' })),
      signature_base64: base64(signIn.signature),
      public_key: signIn.publicKey.toString(),
    },
    quote: {
      quote_json: nearQuoteJson(quote),
      signature_base64: quoteSignature,
      msg,
    },
    delegate: {
      tag: 2 ** 30 + 366,
      sender_id: payer,
      receiver_id: 'test-usdc.testnet',
      method_name: 'ft_transfer_call',
      args_json: JSON.stringify(args),
      gas: '100000000000000',
      deposit: '1',
      nonce: '190000000000042',
      max_block_height: '190000300',
      public_key: payerKey.getPublicKey().toString(),
      encoded_hex: hex(encoded),
      hash_hex: hex(delegateHash),
      signature_base64: base64(signedDelegate.signature.data),
      signed_delegate_base64: base64(encodeSignedDelegate(signedDelegate)),
    },
  };
  return `${JSON.stringify(vectors, null, 2)}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(VECTORS_PATH, await renderNearVectors());
  console.log(`Wrote ${VECTORS_PATH}`);
}
