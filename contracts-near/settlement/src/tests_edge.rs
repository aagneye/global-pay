#[test]
fn payouts_refuse_one_gas_unit_below_40_tgas_with_nothing_changed() {
    let mut contract = setup();
    pay(&mut contract, &quote(1));
    let just_short = Gas::from_gas(MIN_GAS_FOR_PAYOUT.as_gas() - 1);

    for payout in [Payout::Settle, Payout::Refund] {
        call_with_gas(operator(), just_short);
        let result = catch(|| match payout {
            Payout::Settle => contract.settle(id(1)),
            Payout::Refund => contract.refund(id(1)),
        });
        let message = result.err().expect("paid out with too little gas");
        assert!(message.contains("attach at least 40 TGas"), "{message}");
        assert!(calls().is_empty());
        assert_eq!(status(&contract, &id(1)), "Paid");
    }

    // With the backend's 100 TGas, the transfer and the rollback callback each get at least
    // their static gas.
    call_with_gas(operator(), Gas::from_tgas(100));
    let _ = contract.refund(id(1));
    assert_eq!(status(&contract, &id(1)), "Refunded");
    let gas: Vec<(String, u64)> = calls().into_iter().map(|c| (c.1, c.4)).collect();
    assert_eq!(gas.len(), 2);
    assert_eq!((gas[0].0.as_str(), gas[1].0.as_str()), ("ft_transfer", "on_payout"));
    assert!(gas[0].1 >= GAS_FOR_FT_TRANSFER.as_gas(), "ft_transfer gas {}", gas[0].1);
    assert!(gas[1].1 >= GAS_FOR_ON_PAYOUT.as_gas(), "on_payout gas {}", gas[1].1);
}

