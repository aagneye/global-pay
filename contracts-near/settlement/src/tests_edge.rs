#[test]
fn refuses_signatures_that_are_not_base64_of_64_bytes() {
    let mut contract = setup();
    let quote_json = quote(1).to_string();
    let good = signature_of(&quote_json, &signer_seed());
    let cases = [
        ("63 bytes", BASE64.encode(&good[..63])),
        ("65 bytes", BASE64.encode([good.to_vec(), vec![0u8]].concat())),
        ("empty", String::new()),
        ("unpadded", STANDARD_NO_PAD.encode(good)),
        ("hex", good.iter().map(|b| format!("{b:02x}")).collect()),
        ("spaces", format!(" {} ", BASE64.encode(good))),
    ];
    for (case, signature) in cases {
        let msg = json!({ "quote": quote_json, "signature": signature }).to_string();
        assert_refused(&mut contract, token(), AMOUNT, msg, "invalid signature encoding", case);
    }
}

#[test]
fn refuses_well_formed_signatures_that_do_not_match_the_quote() {
    let mut contract = setup();
    let quote_json = quote(1).to_string();
    let pretty = serde_json::to_string_pretty(&quote(1)).unwrap();
    let msg_of = |signature: [u8; 64]| {
        json!({ "quote": quote_json, "signature": BASE64.encode(signature) }).to_string()
    };
    let cases = [
        ("all zero", [0u8; 64]),
        ("another quote's signature", signature_of(&quote(2).to_string(), &signer_seed())),
        ("signed pretty-printed", signature_of(&pretty, &signer_seed())),
        ("signed with a 0x-less id", signature_of(&quote_json.replace("0x", ""), &signer_seed())),
        ("another key", signature_of(&quote_json, &[3u8; 32])),
        ("flipped bit", {
            let mut sig = signature_of(&quote_json, &signer_seed());
            sig[10] ^= 1;
            sig
        }),
    ];
    for (case, signature) in cases {
        assert_refused(&mut contract, token(), AMOUNT, msg_of(signature), "invalid quote signature", case);
    }

    // The signature covers exact bytes: the same quote re-formatted no longer verifies.
    let signature = signature_of(&quote_json, &signer_seed());
    let msg = json!({ "quote": pretty, "signature": BASE64.encode(signature) }).to_string();
    assert_refused(&mut contract, token(), AMOUNT, msg, "invalid quote signature", "reformatted");

    // The signature is checked before the fields: a bad quote with a bad signature says so.
    let msg = json!({ "quote": "{}", "signature": BASE64.encode([0u8; 64]) }).to_string();
    assert_refused(&mut contract, token(), AMOUNT, msg, "invalid quote signature", "bad both");
}

