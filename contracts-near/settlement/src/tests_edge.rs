#[test]
fn accepts_an_inr_quote_next_to_a_thb_one() {
    let mut contract = setup();
    pay(&mut contract, &quote(1));

    let mut inr = quote(2);
    inr["fiat_currency"] = json!("INR");
    inr["fiat_amount"] = json!("50000"); // 500.00 rupees in paise
    call_as(token());
    assert_kept_all(contract.ft_on_transfer(payer(), U128(AMOUNT), sign_msg(&inr)));
    let logged = events();
    assert_eq!(logged.len(), 1);
    assert_eq!(logged[0]["event"], "payment_received");
    assert_eq!(logged[0]["data"][0]["fiat_currency"], "INR");
    assert_eq!(logged[0]["data"][0]["fiat_amount"], "50000");

    let payment = contract.get_payment(id(2)).unwrap();
    assert_eq!((payment.fiat_currency.as_str(), payment.fiat_amount), ("INR", U128(50_000)));
    let page: Vec<(String, String)> =
        contract.get_paid_events(0, 10).into_iter().map(|p| (p.quote_id, p.fiat_currency)).collect();
    assert_eq!(page, vec![(id(1), "THB".to_owned()), (id(2), "INR".to_owned())]);

    // An INR payment settles like any other.
    call_as(operator());
    let _ = contract.settle(id(2));
    assert_eq!(status(&contract, &id(2)), "Settled");
    assert_eq!(status(&contract, &id(1)), "Paid");
}

#[test]
fn refuses_currencies_that_are_not_three_uppercase_ascii_letters() {
    let mut contract = setup();
    // "₹" is 3 bytes long but not 3 letters; "ＩＮＲ" is full-width.
    for (n, currency) in
        ["inr", "Inr", "iNR", "IN", "I", "", "INRR", "IN1", "IN ", " IN", "I-R", "₹", "ÀB", "ＩＮＲ"]
            .into_iter()
            .enumerate()
    {
        let mut q = quote(n as u64 + 1);
        q["fiat_currency"] = json!(currency);
        assert_refused(
            &mut contract,
            token(),
            AMOUNT,
            sign_msg(&q),
            "invalid fiat_currency",
            &format!("currency {currency:?}"),
        );
    }
}

// ------------------------------------------------------------------------- expiry

#[test]
fn expiry_is_exact_to_the_nanosecond() {
    let mut contract = setup();
    let expires_at_ms = NOW_MS + 60_000;

    // block_timestamp_ms truncates: 1 ns before the expiry millisecond is still before it.
    let mut builder = context(token(), 0);
    builder.block_timestamp(expires_at_ms * 1_000_000 - 1);
    testing_env!(builder.build());
    assert_kept_all(contract.ft_on_transfer(payer(), U128(AMOUNT), sign_msg(&quote(1))));

    let mut builder = context(token(), 0);
    builder.block_timestamp(expires_at_ms * 1_000_000);
    testing_env!(builder.build());
    let result = catch(|| contract.ft_on_transfer(payer(), U128(AMOUNT), sign_msg(&quote(2))));
    let message = result.err().expect("accepted at the expiry nanosecond");
    assert!(message.contains("quote expired"), "{message}");
    assert_eq!(contract.paid_count(), 1);
}

#[test]
fn accepts_the_largest_expiry_and_refuses_bad_expiry_values() {
    let mut contract = setup();
    let mut forever = quote(1);
    forever["expires_at_ms"] = json!(u64::MAX);
    pay(&mut contract, &forever);
    assert_eq!(status(&contract, &id(1)), "Paid");

    let mut past = quote(2);
    past["expires_at_ms"] = json!(0);
    assert_refused(&mut contract, token(), AMOUNT, sign_msg(&past), "quote expired", "expiry 0");

    for (n, raw) in [
        (3, "\"1800000060000\""),      // a string, not a number
        (4, "-1"),                     // negative
        (5, "18446744073709551616"),   // u64::MAX + 1
        (6, "1800000060000.5"),        // fractional
        (7, "null"),
    ] {
        assert_refused(
            &mut contract,
            token(),
            AMOUNT,
            sign_json(&quote_with_raw(n, "expires_at_ms", raw)),
            "invalid quote",
            &format!("expires_at_ms {raw}"),
        );
    }
}

