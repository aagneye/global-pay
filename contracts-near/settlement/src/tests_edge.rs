//! Edge cases on near-sdk's mocked blockchain, next to the main suite in `tests.rs`.
//! Quote signatures are real ed25519 signatures, checked by the mocked `ed25519_verify`.
//!
//! Refusals are caught with `catch_unwind`, so one test can run a table of bad inputs and then
//! check that nothing was recorded.

use super::*;
use ed25519_dalek::{Signer, SigningKey};
use near_sdk::base64::engine::general_purpose::{STANDARD as BASE64, STANDARD_NO_PAD};
use near_sdk::base64::Engine;
use near_sdk::mock::MockAction;
use near_sdk::serde_json::{self, json, Value};
use near_sdk::test_utils::{get_created_receipts, get_logs, VMContextBuilder};
use near_sdk::{test_vm_config, testing_env, PromiseResult, RuntimeFeesConfig};
use std::panic::{catch_unwind, AssertUnwindSafe};

// ------------------------------------------------- helpers (small copies from tests.rs)

/// Generated by tests/fixtures/make_quote.mjs (TEST-ONLY keys).
const FIXTURE: &str = include_str!("../tests/fixtures/quote.json");
const NOW_MS: u64 = 1_800_000_000_000;
const AMOUNT: u128 = 2_850_000;

fn fixture() -> Value {
    serde_json::from_str(FIXTURE).unwrap()
}

fn account(id: &str) -> AccountId {
    id.parse().unwrap()
}

fn owner() -> AccountId {
    account("owner.testnet")
}
fn operator() -> AccountId {
    account("relayer.testnet")
}
fn treasury() -> AccountId {
    account("treasury.testnet")
}
fn stranger() -> AccountId {
    account("mallory.testnet")
}
fn settlement_id() -> AccountId {
    account(fixture()["settlement"].as_str().unwrap())
}
fn token() -> AccountId {
    account(fixture()["token"].as_str().unwrap())
}
fn payer() -> AccountId {
    account(fixture()["payer"]["account_id"].as_str().unwrap())
}

fn signer_seed() -> [u8; 32] {
    let hex = fixture()["quote_signer"]["seed_hex"].as_str().unwrap().to_owned();
    let bytes: Vec<u8> =
        (0..hex.len()).step_by(2).map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap()).collect();
    bytes.try_into().unwrap()
}

fn context(predecessor: AccountId, now_ms: u64) -> VMContextBuilder {
    let mut builder = VMContextBuilder::new();
    builder
        .current_account_id(settlement_id())
        .signer_account_id(predecessor.clone())
        .predecessor_account_id(predecessor)
        .block_timestamp(now_ms * 1_000_000)
        .block_height(42);
    builder
}

fn call_as(predecessor: AccountId) {
    testing_env!(context(predecessor, NOW_MS).build());
}

fn call_with_gas(predecessor: AccountId, gas: Gas) {
    testing_env!(context(predecessor, NOW_MS).prepaid_gas(gas).build());
}

fn callback_with(result: PromiseResult) {
    testing_env!(
        context(settlement_id(), NOW_MS).build(),
        test_vm_config(),
        RuntimeFeesConfig::test(),
        Default::default(),
        vec![result],
    );
}

fn setup() -> Settlement {
    call_as(owner());
    Settlement::new(
        owner(),
        operator(),
        treasury(),
        token(),
        fixture()["quote_signer"]["public_key"].as_str().unwrap().to_owned(),
    )
}

fn id(n: u64) -> String {
    format!("0x{n:064x}")
}

fn quote(n: u64) -> Value {
    json!({
        "quote_id": id(n),
        "payer": payer(),
        "token": token(),
        "token_amount": AMOUNT.to_string(),
        "fiat_currency": "THB",
        "fiat_amount": "10000",
        "merchant_ref_hash": format!("0x{}", "11".repeat(32)),
        "expires_at_ms": NOW_MS + 60_000,
    })
}

fn signature_of(text: &str, seed: &[u8; 32]) -> [u8; 64] {
    SigningKey::from_bytes(seed).sign(text.as_bytes()).to_bytes()
}

/// ed25519 over the exact bytes of `quote_json`, as the backend signs.
fn sign_json(quote_json: &str) -> String {
    let signature = signature_of(quote_json, &signer_seed());
    json!({ "quote": quote_json, "signature": BASE64.encode(signature) }).to_string()
}

fn sign_msg(quote: &Value) -> String {
    sign_json(&quote.to_string())
}

fn assert_kept_all(result: PromiseOrValue<U128>) {
    match result {
        PromiseOrValue::Value(U128(0)) => {}
        PromiseOrValue::Value(U128(n)) => panic!("returned {n} unused tokens"),
        PromiseOrValue::Promise(_) => panic!("returned a promise"),
    }
}

fn pay(contract: &mut Settlement, quote: &Value) {
    call_as(token());
    let amount = quote["token_amount"].as_str().unwrap().parse().unwrap();
    assert_kept_all(contract.ft_on_transfer(payer(), U128(amount), sign_msg(quote)));
}

fn status(contract: &Settlement, quote_id: &str) -> String {
    contract.get_payment(quote_id.to_owned()).unwrap().status
}

fn events() -> Vec<Value> {
    get_logs()
        .iter()
        .filter_map(|log| log.strip_prefix("EVENT_JSON:"))
        .map(|json| serde_json::from_str(json).unwrap())
        .collect()
}

/// (receiver, method, args, deposit in yocto, static gas) of each call the contract created.
fn calls() -> Vec<(String, String, Value, u128, u64)> {
    get_created_receipts()
        .into_iter()
        .flat_map(|receipt| {
            let receiver = receipt.receiver_id.to_string();
            receipt.actions.into_iter().filter_map(move |action| match action {
                MockAction::FunctionCallWeight {
                    method_name, args, attached_deposit, prepaid_gas, ..
                } => Some((
                    receiver.clone(),
                    String::from_utf8(method_name).unwrap(),
                    serde_json::from_slice(&args).unwrap(),
                    attached_deposit.as_yoctonear(),
                    prepaid_gas.as_gas(),
                )),
                _ => None,
            })
        })
        .collect()
}

/// Runs `f` and returns its panic message, or `Ok` if it did not panic.
fn catch<R>(f: impl FnOnce() -> R) -> Result<R, String> {
    catch_unwind(AssertUnwindSafe(f)).map_err(|e| {
        e.downcast_ref::<String>()
            .cloned()
            .or_else(|| e.downcast_ref::<&str>().map(|s| (*s).to_owned()))
            .unwrap_or_else(|| "<non-string panic>".to_owned())
    })
}

/// Delivers `msg` as `caller` and expects a refusal containing `expected`, with nothing
/// recorded: same paid count, no events.
fn assert_refused(
    contract: &mut Settlement,
    caller: AccountId,
    amount: u128,
    msg: String,
    expected: &str,
    case: &str,
) {
    let before = contract.paid_count();
    call_as(caller);
    let result = catch(|| contract.ft_on_transfer(payer(), U128(amount), msg));
    match result {
        Ok(_) => panic!("{case}: accepted, expected a refusal with {expected:?}"),
        Err(message) => {
            assert!(message.contains(expected), "{case}: got {message:?}, expected {expected:?}")
        }
    }
    assert_eq!(contract.paid_count(), before, "{case}: a refused transfer was recorded");
    assert!(events().is_empty(), "{case}: a refused transfer logged an event");
}

/// A signed quote with one field replaced by raw JSON text (for values `json!` cannot build).
fn quote_with_raw(n: u64, field: &str, raw: &str) -> String {
    let mut q = quote(n);
    q[field] = json!("__RAW__");
    q.to_string().replace("\"__RAW__\"", raw)
}

