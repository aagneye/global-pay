#[test]
fn paging_survives_extreme_cursors() {
    let mut contract = setup();
    for n in 1..=3 {
        pay(&mut contract, &quote(n));
    }
    let page = |from, limit| -> Vec<u64> {
        contract.get_paid_events(from, limit).into_iter().map(|p| p.index).collect()
    };
    assert_eq!(page(u64::MAX, u64::MAX), Vec::<u64>::new());
    assert_eq!(page(u64::MAX, 1), Vec::<u64>::new());
    assert_eq!(page(u64::MAX - 1, 2), Vec::<u64>::new());
    assert_eq!(page(2, u64::MAX), vec![2]);
    assert_eq!(page(3, 0), Vec::<u64>::new());
    assert_eq!(page(1, 0), Vec::<u64>::new());
    assert_eq!(page(0, 3), vec![0, 1, 2]);
}

#[test]
fn an_indexer_walking_pages_sees_every_payment_once_in_order() {
    let mut contract = setup();
    let ids: Vec<u64> = (0..23).map(|n| 1000 - n * 7).collect();
    for &n in &ids {
        pay(&mut contract, &quote(n));
    }
    assert_eq!(contract.paid_count(), 23);

    let mut cursor = 0;
    let mut seen = Vec::new();
    loop {
        let page = contract.get_paid_events(cursor, 10);
        if page.is_empty() {
            break;
        }
        assert!(page.len() <= 10);
        for (offset, payment) in page.iter().enumerate() {
            assert_eq!(payment.index, cursor + offset as u64);
        }
        cursor += page.len() as u64;
        seen.extend(page.into_iter().map(|p| p.quote_id));
    }
    assert_eq!(cursor, contract.paid_count());
    assert_eq!(seen, ids.iter().map(|&n| id(n)).collect::<Vec<_>>());
}

