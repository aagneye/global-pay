#[test]
fn a_confirmed_payout_is_final() {
    let mut contract = setup();
    pay(&mut contract, &quote(1));
    pay(&mut contract, &quote(2));

    call_as(operator());
    let _ = contract.settle(id(1));
    callback_with(PromiseResult::Successful(vec![]));
    assert!(contract.on_payout(id(1), Payout::Settle));
    call_as(operator());
    let _ = contract.refund(id(2));
    callback_with(PromiseResult::Successful(vec![]));
    assert!(contract.on_payout(id(2), Payout::Refund));

    for (quote_id, done) in [(id(1), "Settled"), (id(2), "Refunded")] {
        for payout in [Payout::Settle, Payout::Refund] {
            call_as(operator());
            let result = catch(|| match payout {
                Payout::Settle => contract.settle(quote_id.clone()),
                Payout::Refund => contract.refund(quote_id.clone()),
            });
            let message = result.err().expect("a finished payment was paid out again");
            assert!(message.contains(&format!("is {done}, not Paid")), "{message}");
            assert!(calls().is_empty(), "a refused payout created a transfer");
        }
        assert_eq!(status(&contract, &quote_id), done);
    }
}

#[test]
fn settle_after_a_failed_refund_pays_the_treasury() {
    let mut contract = setup();
    pay(&mut contract, &quote(1));
    call_as(operator());
    let _ = contract.refund(id(1));
    callback_with(PromiseResult::Failed);
    assert!(!contract.on_payout(id(1), Payout::Refund));
    let logged = events();
    assert_eq!(logged[0]["event"], "payout_failed");
    assert_eq!(logged[0]["data"][0]["receiver_id"], json!(payer()));
    assert_eq!(status(&contract, &id(1)), "Paid");

    call_as(operator());
    let _ = contract.settle(id(1));
    let calls = calls();
    assert_eq!(calls[0].2["receiver_id"], json!(treasury()));
    callback_with(PromiseResult::Successful(vec![]));
    assert!(contract.on_payout(id(1), Payout::Settle));
    let logged = events();
    assert_eq!(logged[0]["event"], "settled");
    assert_eq!(logged[0]["data"][0]["receiver_id"], json!(treasury()));
    assert_eq!(status(&contract, &id(1)), "Settled");
}

