#[test]
fn handles_u128_max_amounts_end_to_end() {
    let mut contract = setup();
    let max = u128::MAX.to_string();
    let mut q = quote(1);
    q["token_amount"] = json!(max);
    q["fiat_amount"] = json!(max);

    // One unit short of the quote is an amount mismatch, not an overflow.
    assert_refused(&mut contract, token(), u128::MAX - 1, sign_msg(&q), "amount mismatch", "MAX-1");

    pay(&mut contract, &q);
    assert_eq!(events()[0]["data"][0]["token_amount"], json!(max));
    let payment = contract.get_payment(id(1)).unwrap();
    assert_eq!((payment.token_amount, payment.fiat_amount), (U128(u128::MAX), U128(u128::MAX)));

    call_as(operator());
    let _ = contract.settle(id(1));
    let calls = calls();
    assert_eq!(calls[0].1, "ft_transfer");
    assert_eq!(calls[0].2["amount"], json!(max));

    callback_with(PromiseResult::Successful(vec![]));
    assert!(contract.on_payout(id(1), Payout::Settle));
    assert_eq!(events()[0]["data"][0]["token_amount"], json!(max));
}

#[test]
fn refuses_amounts_that_overflow_or_are_not_decimal_strings() {
    let mut contract = setup();
    let cases = [
        ("token_amount", "\"340282366920938463463374607431768211456\""), // u128::MAX + 1
        ("token_amount", "\"-1\""),
        ("token_amount", "\"1e6\""),
        ("token_amount", "\"2850000.0\""),
        ("token_amount", "\"0x2b7cd0\""),
        ("token_amount", "\"\""),
        ("token_amount", "\" 2850000\""),
        ("token_amount", "null"),
        ("fiat_amount", "\"340282366920938463463374607431768211456\""),
        ("fiat_amount", "\"-10000\""),
        ("fiat_amount", "10000"), // a JSON number, not a string
    ];
    for (n, (field, raw)) in cases.into_iter().enumerate() {
        assert_refused(
            &mut contract,
            token(),
            AMOUNT,
            sign_json(&quote_with_raw(n as u64 + 1, field, raw)),
            "invalid quote",
            &format!("{field} {raw}"),
        );
    }

    // Zero is refused even when the transfer is zero too.
    let mut zero = quote(99);
    zero["token_amount"] = json!("0");
    assert_refused(
        &mut contract,
        token(),
        0,
        sign_msg(&zero),
        "token_amount must be greater than zero",
        "zero",
    );
}

