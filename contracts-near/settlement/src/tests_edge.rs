#[test]
fn a_quote_cannot_be_replayed_after_settle_refund_or_a_failed_payout() {
    let mut contract = setup();
    for n in 1..=3 {
        pay(&mut contract, &quote(n));
    }
    call_as(operator());
    let _ = contract.settle(id(1));
    callback_with(PromiseResult::Successful(vec![]));
    assert!(contract.on_payout(id(1), Payout::Settle));

    call_as(operator());
    let _ = contract.refund(id(2));
    callback_with(PromiseResult::Successful(vec![]));
    assert!(contract.on_payout(id(2), Payout::Refund));

    call_as(operator());
    let _ = contract.settle(id(3));
    callback_with(PromiseResult::Failed);
    assert!(!contract.on_payout(id(3), Payout::Settle));

    for n in 1..=3 {
        assert_refused(
            &mut contract,
            token(),
            AMOUNT,
            sign_msg(&quote(n)),
            "quote already used",
            &format!("replay of quote {n}"),
        );
    }
    assert_eq!(contract.paid_count(), 3);
    assert_eq!(status(&contract, &id(1)), "Settled");
    assert_eq!(status(&contract, &id(2)), "Refunded");
    assert_eq!(status(&contract, &id(3)), "Paid");
}

