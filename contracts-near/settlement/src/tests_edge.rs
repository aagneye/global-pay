#[test]
fn only_the_configured_token_can_deliver_a_payment() {
    let mut contract = setup();
    let callers = [
        payer(),
        operator(),
        owner(),
        treasury(),
        stranger(),
        settlement_id(),
        account(&format!("x{}", token())),
        account(&format!("sub.{}", token())),
    ];
    for caller in callers {
        let case = format!("caller {caller}");
        assert_refused(
            &mut contract,
            caller.clone(),
            AMOUNT,
            sign_msg(&quote(1)),
            "only the configured token can call ft_on_transfer",
            &case,
        );
        // The caller is checked before the msg is even parsed.
        assert_refused(
            &mut contract,
            caller,
            AMOUNT,
            "garbage".to_owned(),
            "only the configured token can call ft_on_transfer",
            &case,
        );
    }
    // The real token still gets through afterwards.
    pay(&mut contract, &quote(1));
    assert_eq!(contract.paid_count(), 1);
}

